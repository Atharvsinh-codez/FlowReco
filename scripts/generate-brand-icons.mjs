const raster = async (svg, output, options = {}) => {
	ensure(path.dirname(output));
	let pipeline = sharp(Buffer.from(svg), { density: options.density ?? 192 });
	if (options.width || options.height) {
		pipeline = pipeline.resize(options.width, options.height, {
			fit: options.fit ?? "fill",
			background: options.background,
		});
	}
	const extension = path.extname(output).toLowerCase();
	if (extension === ".jpg" || extension === ".jpeg") {
		pipeline = pipeline
			.flatten({ background: options.background ?? "#F4F5F6" })
			.jpeg({
				quality: options.quality ?? 92,
				chromaSubsampling: "4:4:4",
			});
	} else if (extension === ".webp") {
		pipeline = pipeline.webp({
			quality: options.quality ?? 92,
			lossless: true,
		});
	} else {
		pipeline = pipeline.png({ compressionLevel: 9, palette: false });
	}
	await pipeline.toFile(output);
};

